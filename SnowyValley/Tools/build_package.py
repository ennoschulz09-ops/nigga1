#!/usr/bin/env python3
"""Build the Roblox package for SNOWY VALLEY.

    python3 SnowyValley/Tools/build_package.py

Reads Metadata/*.json (written by the Blender generator) and the Luau sources
in Roblox/src, then writes
  * Roblox/src/Shared/Data/*.luau, Roblox/src/Server/Data/*.luau
      data ModuleScripts (HttpService:JSONDecode of the embedded JSON)
  * Roblox/tests/fixtures/*.luau   plain Luau tables for the CLI test runner
  * Roblox/src/Server/Tests/*.luau Studio test runner (+ copy of tests/specs)
  * Roblox/SnowyValley.rbxmx       install bundle (insert into ServerStorage)
  * Roblox/sourcemap.json          DataModel map for luau-lsp type checking
"""

import json
import os
import re
import shutil
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
META = os.path.join(ROOT, "Metadata")
RBX = os.path.join(ROOT, "Roblox")
SRC = os.path.join(RBX, "src")

SHARED_DATA = ["RouteData", "Checkpoints", "GondolaData", "Environment"]
SERVER_DATA = ["AssetManifest", "CollisionData"]


def load(name):
    with open(os.path.join(META, name + ".json")) as f:
        return json.load(f)


def generator_version():
    try:
        return load("AssetManifest").get("version", "?")
    except FileNotFoundError:
        return "?"


def long_string(text):
    level = 1
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    return "[%s[%s]%s]" % (eq, text, eq)


def write_data_module(name, out_dir):
    data = load(name)
    text = json.dumps(data, separators=(",", ":"))
    src = ("-- AUTO-GENERATED by Tools/build_package.py from Metadata/%s.json - do not edit.\n"
           "-- Snowy Valley generator %s\n"
           "local HttpService = game:GetService(\"HttpService\")\n"
           "return HttpService:JSONDecode(%s)\n" % (name, generator_version(), long_string(text)))
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, name + ".luau"), "w") as f:
        f.write(src)
    return len(src)


IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LUAU_KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
                 "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while", "continue",
                 "export", "type", "typeof"}


def to_luau(v):
    if v is None:
        return "nil"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        r = repr(float(v)) if isinstance(v, float) else str(v)
        return r if r not in ("nan", "inf", "-inf") else "0"
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "{" + ",".join(to_luau(x) for x in v) + "}"
    if isinstance(v, dict):
        parts = []
        for k, x in v.items():
            if x is None:
                continue
            key = k if IDENT.match(k) and k not in LUAU_KEYWORDS else "[%s]" % json.dumps(k)
            parts.append("%s=%s" % (key, to_luau(x)))
        return "{" + ",".join(parts) + "}"
    raise TypeError(type(v))


def write_fixture(name):
    d = os.path.join(RBX, "tests", "fixtures")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, name + ".luau"), "w") as f:
        f.write("-- AUTO-GENERATED test fixture from Metadata/%s.json\nreturn %s\n" % (name, to_luau(load(name))))


STUDIO_RUNNER = '''--!strict
-- Snowy Valley - logic tests in Studio (same specs as the CLI runner).
-- Command bar:  require(game.ServerStorage.SnowyValleyServer.Tests.RunTests)()
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Shared = ReplicatedStorage:WaitForChild("SnowyValleyShared")

return function(): (number, number)
	local specs = require(script.Parent:WaitForChild("Specs")) :: any
	local passed, failed = 0, 0
	local t = {
		check = function(cond: boolean, msg: string)
			if cond then
				passed += 1
				print("[SnowyValley test] PASS " .. msg)
			else
				failed += 1
				warn("[SnowyValley test] FAIL " .. msg)
			end
		end,
		info = function(msg: string)
			print("[SnowyValley test] info " .. msg)
		end,
	}
	specs(t, {
		RouteGraph = require(Shared:WaitForChild("RouteGraph")),
		CheckpointTracker = require(Shared:WaitForChild("CheckpointTracker")),
		RouteData = require(Shared.Data:WaitForChild("RouteData")),
		Checkpoints = require(Shared.Data:WaitForChild("Checkpoints")),
	})
	print(string.format("[SnowyValley test] %d passed, %d failed", passed, failed))
	return passed, failed
end
'''


def write_studio_tests():
    d = os.path.join(SRC, "Server", "Tests")
    os.makedirs(d, exist_ok=True)
    shutil.copyfile(os.path.join(RBX, "tests", "specs.luau"), os.path.join(d, "Specs.luau"))
    with open(os.path.join(d, "RunTests.luau"), "w") as f:
        f.write(STUDIO_RUNNER)


# ---------------------------------------------------------------------------
# DataModel layout of the package
# ---------------------------------------------------------------------------

def script_class(fname):
    if fname.endswith(".server.luau"):
        return "Script", fname[: -len(".server.luau")]
    if fname.endswith(".client.luau"):
        return "LocalScript", fname[: -len(".client.luau")]
    return "ModuleScript", fname[: -len(".luau")]


def tree_from_dir(path, name, cls="Folder"):
    node = dict(name=name, cls=cls, children=[], file=None)
    for entry in sorted(os.listdir(path)):
        full = os.path.join(path, entry)
        if os.path.isdir(full):
            node["children"].append(tree_from_dir(full, entry))
        elif entry.endswith(".luau"):
            c, n = script_class(entry)
            node["children"].append(dict(name=n, cls=c, children=[], file=full))
    return node


def package_tree():
    return dict(name="SnowyValleyInstall", cls="Folder", file=None, children=[
        dict(name="Install", cls="ModuleScript", children=[], file=os.path.join(SRC, "Install", "Install.luau")),
        dict(name="ReplicatedStorage", cls="Folder", file=None,
             children=[tree_from_dir(os.path.join(SRC, "Shared"), "SnowyValleyShared")]),
        dict(name="ServerStorage", cls="Folder", file=None,
             children=[tree_from_dir(os.path.join(SRC, "Server"), "SnowyValleyServer")]),
        dict(name="ServerScriptService", cls="Folder", file=None,
             children=[dict(name="SnowyValleyBootstrap", cls="Script", children=[], disabled=True,
                            file=os.path.join(SRC, "ServerScripts", "SnowyValleyBootstrap.server.luau"))]),
        dict(name="StarterPlayerScripts", cls="Folder", file=None,
             children=[dict(name="SnowyValleyGondola", cls="LocalScript", children=[],
                            file=os.path.join(SRC, "ClientScripts", "SnowyValleyGondola.client.luau"))]),
    ])


def cdata(text):
    return "<![CDATA[" + text.replace("]]>", "]]]]><![CDATA[>") + "]]>"


def write_rbxmx(tree, path):
    counter = [0]
    lines = ['<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" '
             'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
             'xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">',
             '\t<Meta name="ExplicitAutoJoints">true</Meta>',
             '\t<External>null</External>', '\t<External>nil</External>']

    def emit(node, depth):
        ind = "\t" * depth
        ref = "RBXSV%05d" % counter[0]
        counter[0] += 1
        lines.append('%s<Item class="%s" referent="%s">' % (ind, node["cls"], ref))
        lines.append("%s\t<Properties>" % ind)
        lines.append('%s\t\t<string name="Name">%s</string>' % (ind, escape(node["name"])))
        if node.get("file"):
            with open(node["file"]) as f:
                src = f.read()
            lines.append('%s\t\t<ProtectedString name="Source">%s</ProtectedString>' % (ind, cdata(src)))
        if node["cls"] in ("Script", "LocalScript"):
            lines.append('%s\t\t<bool name="Disabled">%s</bool>' % (ind, "true" if node.get("disabled") else "false"))
        lines.append("%s\t</Properties>" % ind)
        for ch in node["children"]:
            emit(ch, depth + 1)
        lines.append("%s</Item>" % ind)

    emit(tree, 1)
    lines.append("</roblox>")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return counter[0]


def sourcemap(tree):
    """Rojo-style sourcemap of the INSTALLED layout, for luau-lsp."""
    def conv(node):
        out = {"name": node["name"], "className": node["cls"]}
        if node.get("file"):
            out["filePaths"] = [os.path.relpath(node["file"], RBX)]
        if node["children"]:
            out["children"] = [conv(c) for c in node["children"]]
        return out

    services = {c["name"]: c for c in tree["children"] if c["cls"] == "Folder"}
    children = []
    for svc in ("ReplicatedStorage", "ServerStorage", "ServerScriptService"):
        children.append({"name": svc, "className": svc, "children": [conv(c) for c in services[svc]["children"]]})
    children.append({"name": "StarterPlayer", "className": "StarterPlayer", "children": [
        {"name": "StarterPlayerScripts", "className": "StarterPlayerScripts",
         "children": [conv(c) for c in services["StarterPlayerScripts"]["children"]]}]})
    return {"name": "SnowyValley", "className": "DataModel", "children": children}


def main():
    sizes = {}
    for n in SHARED_DATA:
        sizes[n] = write_data_module(n, os.path.join(SRC, "Shared", "Data"))
    for n in SERVER_DATA:
        sizes[n] = write_data_module(n, os.path.join(SRC, "Server", "Data"))
    for n in ("RouteData", "Checkpoints"):
        write_fixture(n)
    write_studio_tests()
    tree = package_tree()
    n_items = write_rbxmx(tree, os.path.join(RBX, "SnowyValley.rbxmx"))
    with open(os.path.join(RBX, "sourcemap.json"), "w") as f:
        json.dump(sourcemap(tree), f, indent=1)
    total = os.path.getsize(os.path.join(RBX, "SnowyValley.rbxmx"))
    print("data modules: " + ", ".join("%s %.0f KB" % (k, v / 1024) for k, v in sizes.items()))
    print("SnowyValley.rbxmx: %d instances, %.2f MB" % (n_items, total / 1048576))


if __name__ == "__main__":
    main()
